const assert=require('node:assert/strict');
const {analysisProgress}=require('../public/assets/analysis.js');
const view={steps:[],decisions:[]};
const state=()=>analysisProgress('r',view);
assert.equal(state().length,8);
assert.deepEqual(state().map(p=>p.status),['ready',...Array(7).fill('locked')]);
view.steps.push({id:'s1',run_id:'r',step:1,status:'running',attempt:1});
assert.equal(state().filter(p=>p.status==='ready').length,0);
view.steps[0].status='failed';
assert.equal(state()[0].status,'ready');
view.steps.push({id:'s1ok',run_id:'r',step:1,status:'completed',attempt:2});
assert.equal(state()[0].status,'completed');
assert.equal(state()[1].status,'ready');
for(let n=2;n<=7;n++)view.steps.push({id:'s'+n,run_id:'r',step:n,status:'completed',attempt:1});
assert.equal(state()[7].status,'locked');
assert.deepEqual(state()[7].missingDecisions,[3,4,5,6,7]);
for(let n=3;n<=7;n++)view.decisions.push({step_id:'s'+n,action:n===5?'reject':n===6?'uncertain':'accept'});
assert.equal(state()[7].status,'ready');
view.steps.push({id:'s8',run_id:'r',step:8,status:'completed',attempt:1});
assert.equal(state().filter(p=>p.status==='completed').length,8);
assert.equal(state().filter(p=>p.status==='ready').length,0);
assert.equal(analysisProgress('other',view)[0].status,'ready');
console.log('PASS ANALYSIS 12 checks: all steps, sequencing, running lock, failed retry, successful retry, decision gate, complete run, run isolation.');
